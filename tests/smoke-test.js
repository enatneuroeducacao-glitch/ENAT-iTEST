// Import-integrity unit checks: source IDs, all 17 disciplines, duplicate handling and limits.
assert.equal(Object.keys(importCore.DISCIPLINES).length, 17);
assert.equal(importCore.normalizeId(" DD0110 ", 2), "DD0110");
assert.equal(importCore.resolveDiscipline("DD0110", "Categoria 0", 2).name, "Direção Defensiva");
assert.equal(importCore.resolveDiscipline("NGCC0001", "Categoria 6", 2).code, "NGCC");
assert.equal(importCore.resolveDiscipline("ENGT0001", "Categoria 12", 2).code, "ENGT");
assert.equal(importCore.resolveDiscipline("NEU0001", "Categoria 15", 2).name, "Neuroeducação Aplicada ao Trânsito");
assert.equal(importCore.resolveDiscipline("PRO0001", "Categoria 16", 2).name, "Formação e Atuação Profissional");
assert.throws(() => importCore.resolveDiscipline("XYZ0001", "Categoria 99", 2), /não foi possível classificar/);
assert.equal(importCore.assertLimits(2 * 1024 * 1024, 1000), true);
assert.throws(() => importCore.assertLimits(2 * 1024 * 1024 + 1, 1), /2 MB/);
assert.throws(() => importCore.assertLimits(100, 1001), /1.000 questões/);
assert.throws(() => importCore.validateBatch([{id:"DD0001"},{id:"dd0001"}], [], "replace"), /ID duplicado/);
assert.throws(() => importCore.validateBatch([{id:"DD0001"}], [{id:"DD0001"}], "append"), /IDs já existentes/);

